bool parse_all_doubles(const std::vector<std::string>& items, std::vector<double>& out) {
    out.clear();
    out.reserve(items.size());
    for (const auto& item : items) {
        try {
            std::size_t used = 0;
            const double value = std::stod(item, &used);
            if (trim(item.substr(used)).empty()) { out.push_back(value); continue; }
        } catch (const std::exception&) {  }
        return false;
    }
    return true;
}
